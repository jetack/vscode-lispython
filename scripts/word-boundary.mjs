// Derives vsc-lispy's completion word boundary from lispython's published spec.
//
//   node scripts/word-boundary.mjs           regenerate the derived files
//   node scripts/word-boundary.mjs --check   exit 1 when either derived file is stale
//
// The one source is test/word-boundary.json, the output of lispython's
// `python -m lispy.word_boundary` (lispython owns the rule: completion_word_span in
// src/lispy/core/parser.py). After lispython changes it, re-run that command into
// test/word-boundary.json, then this script. It writes:
//   - src/wordBoundaryRule.ts: the rule tables and JS-ready regex sources that
//     completionWordSpan (src/nreplCore.ts) implements the spec steps over;
//   - the "wordPattern" of language-configuration.json, the same boundary as one regex
//     for VS Code's own word lookup (word highlight, suggest's re-ask and refilter).
// Every Python-to-JS regex translation lives here, nowhere else.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_PATH = path.join(ROOT, 'test', 'word-boundary.json');
const RULE_PATH = path.join(ROOT, 'src', 'wordBoundaryRule.ts');
const LANGUAGE_CONFIG_PATH = path.join(ROOT, 'language-configuration.json');
const GENERATED = 'generated by scripts/word-boundary.mjs from test/word-boundary.json; do not edit';

// The steps completionWordSpan and the wordPattern below implement are this version's.
// A new version may change the steps' prose, so it fails here until both are reviewed.
const SPEC_VERSION = 3;

// --- Python re (over str) to JS (u flag) ---------------------------------------------

// Python's \w over str is str.isalnum() or '_', and str.isalnum() is any letter (Lu Ll
// Lt Lm Lo) or numeric character (Nd Nl No): \p{L}\p{N}. Python's \d is Unicode Nd.
// JS \p{} follows the running engine's Unicode version, not the spec's `rule.unicode`, so
// a letter or digit assigned in only one of the two versions may classify differently.
const ALNUM_CLASS_BODY = '\\p{L}\\p{N}';
const WORD_CLASS_BODY = `${ALNUM_CLASS_BODY}_`;
const DIGIT_CLASS_BODY = '\\p{Nd}';
// Characters a u-mode JS regex accepts escaped (outside a class / inside one).
const SYNTAX_CHARS = '^$\\.*+?()[]{}|/';
const CLASS_ESCAPABLE = `${SYNTAX_CHARS}-`;

/**
 * The JS (u flag) source of the Python `re` pattern `py`. Only the constructs the spec
 * uses are translated; anything else throws, so a new construct is reviewed rather than
 * silently mistranslated (\s above all: JS \s is not Python's isspace).
 */
function translatePythonRegex(py) {
    let out = '';
    let inClass = false;
    for (let i = 0; i < py.length; i++) {
        const c = py[i];
        if (c === '\\') {
            const n = py[++i];
            if (n === 'd') out += DIGIT_CLASS_BODY; // a \p escape stands alone or in a class
            else if (n === 'w') out += inClass ? WORD_CLASS_BODY : `[${WORD_CLASS_BODY}]`;
            else if (n !== undefined && (inClass ? CLASS_ESCAPABLE : SYNTAX_CHARS).includes(n)) out += `\\${n}`;
            else if (n === '-') out += '-';
            else throw new Error(`untranslated escape \\${n} in ${py}`);
        } else if (inClass) {
            if (c === '[') throw new Error(`nested [ in a class in ${py}`);
            if (c === ']') inClass = false;
            out += c;
        } else if (c === '[') {
            if (py[i + 1] === ']' || (py[i + 1] === '^' && py[i + 2] === ']')) throw new Error(`leading ] in a class in ${py}`);
            inClass = true;
            out += c;
        } else if (c === '(' && py[i + 1] === '?') {
            const group = ['(?:', '(?=', '(?!', '(?<=', '(?<!'].find((g) => py.startsWith(g, i));
            if (group === undefined) throw new Error(`untranslated group at ${i} in ${py}`);
            out += group;
            i += group.length - 1;
        } else if ('.^$'.includes(c)) {
            throw new Error(`untranslated ${c} in ${py}: its semantics differ between Python and JS`);
        } else {
            out += c;
        }
    }
    if (inClass) throw new Error(`unterminated class in ${py}`);
    new RegExp(out, 'u');
    return out;
}

/** `s` as a literal in a u-mode JS regex. */
function literal(s) {
    return [...s].map((c) => (SYNTAX_CHARS.includes(c) ? `\\${c}` : codePointEscape(c, false))).join('');
}

/** `c` as regex source: printable ASCII as is, anything else as a \u escape. */
function codePointEscape(c, inClass) {
    const cp = c.codePointAt(0);
    if (inClass && CLASS_ESCAPABLE.includes(c)) return `\\${c}`;
    if (cp > 0x20 && cp < 0x7f) return c;
    return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`;
}

/** The body of a character class holding exactly `chars` (no JS \s: see the header of the rule file). */
function classBody(chars) {
    return chars.map((c) => codePointEscape(c, true)).join('');
}

const byLengthDesc = (xs) => [...xs].sort((a, b) => [...b].length - [...a].length);
const combos = (heads, tails) => byLengthDesc(heads.flatMap((h) => tails.map((t) => h + t)));
const alt = (sources) => `(?:${sources.join('|')})`;

/**
 * A regex matching what the lexer matches when it tries the literal `entries` in order
 * and takes the first one that matches followed by `tail` (a lookahead source): entry k
 * is excluded where an earlier entry sharing its start also matches. Only an entry that
 * is a prefix of entry k or has entry k as a prefix can match where entry k does, and
 * an entry with an earlier prefix of itself is still reachable (the earlier one's tail
 * may fail), so both relations exclude. `keep` drops branches after the exclusions are
 * built from the full list.
 */
function firstOf(entries, tail = '', keep = () => true) {
    return alt(entries.flatMap((entry, k) => {
        if (!keep(entry)) return [];
        const earlier = entries.slice(0, k).filter((e) => e.startsWith(entry) || entry.startsWith(e));
        const exclude = earlier.length ? `(?!${alt(earlier.map(literal))}${tail})` : '';
        return [`${exclude}${literal(entry)}${tail}`];
    }));
}

// --- the spec ------------------------------------------------------------------------

function readSpec() {
    const spec = JSON.parse(fs.readFileSync(SPEC_PATH, 'utf8'));
    if (spec.version !== SPEC_VERSION) {
        throw new Error(`test/word-boundary.json is spec version ${spec.version}; this generator implements ` +
            `version ${SPEC_VERSION}. Review the spec steps against completionWordSpan and the wordPattern, then bump SPEC_VERSION.`);
    }
    if (spec.columns !== 'code points') throw new Error(`unexpected columns: ${spec.columns}`);
    return spec;
}

/** The rule as JS-ready tables and regex sources: the body of wordBoundaryRule(). */
function jsRule(rule) {
    const stopChars = rule.stopChars.join('');
    const formEndChars = rule.formEndChars.join('');
    for (const c of rule.stopChars) if (c.codePointAt(0) > 0xffff) throw new Error('an astral stop char: the UTF-16 walk assumes BMP');
    return {
        stopChars,
        formEndChars,
        stopClass: classBody(rule.stopChars),
        formEndClass: classBody(rule.formEndChars),
        alnum: `[${ALNUM_CLASS_BODY}]`,
        wrappers: byLengthDesc(rule.wrappers),
        openings: byLengthDesc(rule.openings),
        metaChars: byLengthDesc(rule.metaChars),
        danglingQuotes: byLengthDesc(rule.danglingQuotes),
        stringOpenings: byLengthDesc(rule.stringOpenings),
        // Spec order, not length order: the peel takes the FIRST entry the token starts with.
        tokenPrefixes: rule.tokenPrefixes,
        signs: rule.signs,
        signPeelFollowers: rule.signPeelFollowers,
        neverPeeled: rule.neverPeeled,
        stringPrefix: translatePythonRegex(rule.stringPrefix),
        numberToken: translatePythonRegex(rule.numberToken),
        signedComplex: translatePythonRegex(rule.signedComplex),
    };
}

// --- the wordPattern -----------------------------------------------------------------

/**
 * The wordPattern: one match per dotted segment of the leaf, so VS Code's word at the
 * caret is the spec's [replaceStart, end]. A segment `[^STOP.]+` is matched only where
 * a lookbehind re-lexes its run from the run's start: run start, the run's leading
 * non-word tokens (each the lexer's choice at its position), the word token's start,
 * its peeled front (each peel the one the spec's peel loop takes), a "nothing more
 * peels" check at the leaf start, then the leaf's earlier segments. A symbol or number
 * token always runs to the run's end, so it is its run's last token and its leaf ends
 * there too. VS Code execs the regex from columns mid-line (getWordAtText's 15-column
 * windows), so a mid-segment start must fail, which this anchoring gives.
 *
 * Where the caret is inside the peeled front (`-|-x`) the spec's word starts at the
 * token, a caret-dependent span no regex can give; the word there is no match.
 *
 * ⚠️ The regex must never match the empty string: VS Code's
 * _findRegexMatchEnclosingPosition (wordHelper.ts) does not advance lastIndex past an
 * empty match and has no time-budget check in its inner loop, so it hangs the editor.
 */
function wordPattern(rule, js) {
    const S = js.stopClass;
    const F = js.formEndClass;
    const notStop = `[^${S}]`;
    const atRunEnd = `(?!${notStop})`; // next is a stop char or the line's end
    const atFormEnd = `(?![^${F}])`; // next is a formEndChars char or the line's end
    const beforeNonFormEnd = `(?=[^${F}])`; // next is a character, not a formEndChars one
    const hasStop = (s) => [...s].some((c) => rule.stopChars.includes(c));

    // Each lexer alternative, as tried at a token start; used whole in a lookahead it
    // answers "does this kind match here".
    const openings = combos(js.wrappers, js.openings);
    const dangling = combos(js.wrappers, js.danglingQuotes);
    const metas = combos(js.wrappers, js.metaChars);
    const badTails = byLengthDesc([...js.openings, ...js.metaChars]);
    const OPEN = alt(openings.map(literal));
    const STR = `${js.stringPrefix}${alt(js.stringOpenings.map(literal))}`;
    const DANG = `${alt(dangling.map(literal))}${atFormEnd}`;
    const META = `${alt(metas.map(literal))}${beforeNonFormEnd}`;
    const BAD = `\\^\\*+(?:${alt(badTails.map(literal))}|${atRunEnd})`;

    // The tokens that can precede the word token in its run: the lexer's choice at its
    // position, and stop-free, since a token holding a stop char reaches the run's end.
    // A dangling quote is followed by a formEndChars char, a stop char: never a lead.
    for (const c of rule.formEndChars) if (!rule.stopChars.includes(c)) throw new Error(`formEnd ${c} is not a stop char`);
    const firstOfNoStop = (entries, tail) => firstOf(entries, tail, (e) => !hasStop(e));
    const leads = [
        firstOfNoStop(openings, ''),
        `(?!${OPEN})${js.stringPrefix}${firstOfNoStop(js.stringOpenings, '')}`,
        `(?!${alt([OPEN, STR, DANG])})${firstOfNoStop(metas, beforeNonFormEnd)}`,
        `(?!${alt([OPEN, STR, DANG, META])})\\^\\*+${firstOfNoStop(badTails, '')}`,
    ];
    const LEADS = `${alt(leads)}*`;
    const WORD_TOKEN_START = `(?!${alt([OPEN, STR, DANG, META, BAD])})`;

    // The peel loop. A peel step checks the rest (to the run's end) whole.
    const NEVER = `${alt(js.neverPeeled.map(literal))}${atRunEnd}`;
    const LONG = `(?=${notStop}{2})`; // at least 2 code points
    const PREFIX_STEP = `(?!${NEVER})${LONG}${firstOf(js.tokenPrefixes)}`;
    const SC_WHOLE = `(?:${js.signedComplex})${atRunEnd}`;
    const NUM_AT_WORD_START = `(?:${js.numberToken})${atFormEnd}`; // the lexer's number test
    const NUM_WHOLE = `(?:${js.numberToken})${atRunEnd}`; // the type after a prefix peel
    const followers = alt([js.alnum, ...js.signPeelFollowers.map(literal)]);
    // A number whose signs are peeled starts with a sign, so only signedComplex blocks it.
    // `signs+` is maximal: a shorter run is followed by a sign, which is no follower.
    const signsStep = (isNumber) =>
        `(?!${NEVER})(?!(?=${isNumber})${SC_WHOLE})${LONG}${alt(js.signs.map(literal))}+(?=${followers})`;
    const noPeel = (isNumber) => `(?!${PREFIX_STEP})(?!${signsStep(isNumber)})`;
    // After a signs peel the rest starts with a follower, which starts no prefix or sign
    // (checked below), so nothing more peels; a prefix peel never leaves a number that
    // starts with a prefix, so prefix peels see a symbol.
    for (const s of [...js.tokenPrefixes, ...js.signs]) {
        if (new RegExp(`^${followers}`, 'u').test(s)) throw new Error(`${s} starts with a sign-peel follower`);
    }
    const FRONT = alt([
        noPeel(NUM_AT_WORD_START),
        signsStep(NUM_AT_WORD_START),
        `(?:${PREFIX_STEP})+${alt([noPeel(NUM_WHOLE), signsStep(NUM_WHOLE)])}`,
    ]);
    const EARLIER_SEGMENTS = `(?:[^${S}.]*\\.)*`;

    // A cheap first check, so the full lookbehind (which re-lexes back to the run's start)
    // runs at few columns: a segment starts after a run start, a lead token, a prefix
    // peel or a `.`, or right after a signs peel. A signs peel ends a maximal signs run
    // (it is followed by a follower, which is no sign) that starts at the word token, so
    // after a run start, a lead token or a prefix peel. ⚠️ Columns inside a signs run must
    // fail here, not in the full lookbehind: there each would re-lex the run, quadratic per
    // exec on a long `---…` line, enough to trip VS Code's time budget.
    const nonSignEnds = new Set();
    for (const e of [...openings, ...metas, ...badTails, ...js.stringOpenings, ...js.tokenPrefixes]) {
        nonSignEnds.add([...e].at(-1));
    }
    const signChars = new Set(js.signs.flatMap((s) => [...s]));
    for (const c of [...nonSignEnds, '.']) {
        if (signChars.has(c)) throw new Error(`${c} both ends a non-sign token and is a sign character`);
    }
    const ends = (chars) => classBody([...chars].filter((c) => !rule.stopChars.includes(c)));
    const SIGNS_RUN = `${alt(js.signs.map(literal))}+`;
    const guard = alt([
        `(?<=^|[${S}${ends([...nonSignEnds, '.'])}])`,
        `(?=${followers})(?<=(?:^|[${S}${ends(nonSignEnds)}])${SIGNS_RUN})`,
    ]);

    const pattern = `${guard}(?<=(?:^|[${S}])${LEADS}${WORD_TOKEN_START}${FRONT}${EARLIER_SEGMENTS})[^${S}.]+`;
    const re = new RegExp(pattern, 'gu');
    if (re.test('') || new RegExp(`^(?:${pattern})$`, 'u').test('')) throw new Error('the wordPattern matches the empty string');
    return pattern;
}

// --- output --------------------------------------------------------------------------

/** `s` as an ASCII-only JS string literal. */
function jsString(s) {
    return `'${[...s].map((c) => {
        if (c === '\\' || c === "'") return `\\${c}`;
        const cp = c.codePointAt(0);
        if (cp >= 0x20 && cp < 0x7f) return c;
        return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`;
    }).join('')}'`;
}

function ruleSource(js) {
    const value = (v) => (Array.isArray(v) ? `[${v.map(jsString).join(', ')}]` : jsString(v));
    const fields = Object.entries(js).map(([k, v]) => `        ${k}: ${value(v)},`).join('\n');
    return `// ${GENERATED}.
//
// lispython's completion word boundary rule (completion_word_span), as tables and JS
// regex sources (u flag) for completionWordSpan in nreplCore.ts. Python's \\d and \\w are
// translated to \\p{Nd} and [\\p{L}\\p{N}_]; the stop and form-end classes list the
// spec's code points, never JS \\s, which differs from Python's isspace.

/** The word boundary rule; a function declaration so it can be injected into the REPL webview. */
export function wordBoundaryRule() {
    return {
${fields}
    };
}
`;
}

/** The end index of the JSON value starting at `i` in `text`. */
function jsonValueEnd(text, i) {
    let depth = 0;
    for (let j = i; j < text.length; j++) {
        const c = text[j];
        if (c === '"') {
            for (j++; text[j] !== '"'; j++) if (text[j] === '\\') j++;
            if (depth === 0) return j + 1;
        } else if (c === '{' || c === '[') depth++;
        else if (c === '}' || c === ']') {
            if (--depth === 0) return j + 1;
        }
    }
    throw new Error('unterminated JSON value');
}

// The marker line this script writes above "wordPattern"; only that line is replaced.
const MARKER = '// wordPattern: generated by scripts/word-boundary.mjs';

function languageConfigSource(current, pattern) {
    const marker = MARKER.replace(/[\\^$.*+?()[\]{}|/]/g, '\\$&');
    const key = new RegExp(`(^[ \\t]*)(?:${marker}[^\\n]*\\n[ \\t]*)?"wordPattern"\\s*:\\s*`, 'm').exec(current);
    if (!key) throw new Error('no "wordPattern" in language-configuration.json');
    const indent = key[1];
    const valueEnd = jsonValueEnd(current, key.index + key[0].length);
    const value = `{\n${indent}  "pattern": ${JSON.stringify(pattern)},\n${indent}  "flags": "u"\n${indent}}`;
    return `${current.slice(0, key.index)}${indent}// wordPattern: ${GENERATED}.\n` +
        `${indent}"wordPattern": ${value}${current.slice(valueEnd)}`;
}

function main() {
    const check = process.argv.includes('--check');
    const spec = readSpec();
    const js = jsRule(spec.rule);
    const pattern = wordPattern(spec.rule, js);
    const outputs = [
        [RULE_PATH, ruleSource(js)],
        [LANGUAGE_CONFIG_PATH, languageConfigSource(fs.readFileSync(LANGUAGE_CONFIG_PATH, 'utf8'), pattern)],
    ];
    const stale = outputs.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text);
    if (check) {
        for (const [file] of stale) console.error(`stale: ${path.relative(ROOT, file)} (run \`bun run word-boundary\`)`);
        process.exit(stale.length ? 1 : 0);
    }
    for (const [file, text] of stale) {
        fs.writeFileSync(file, text);
        console.log(`wrote ${path.relative(ROOT, file)}`);
    }
}

main();
