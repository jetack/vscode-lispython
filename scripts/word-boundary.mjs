// The steps completionWordSpan and the wordPattern below implement are this version's.
// A new version may change the steps' prose, so it fails here until both are reviewed.
const SPEC_VERSION = 7;

// --- Python re (over str) to JS (u flag) ---------------------------------------------

// Python's \w over str is str.isalnum() or '_', and str.isalnum() is any letter (Lu Ll
// Lt Lm Lo) or numeric character (Nd Nl No): \p{L}\p{N}. Python's \d is Unicode Nd.
// JS \p{} follows the running JS engine's Unicode tables and Python's \w/\d follow the
// running Python's, so a letter or digit assigned in only one of the two versions may
// classify differently (the spec itself names no Unicode version).
const ALNUM_CLASS_BODY = '\\p{L}\\p{N}';
const WORD_CLASS_BODY = `${ALNUM_CLASS_BODY}_`;
const DIGIT_CLASS_BODY = '\\p{Nd}';
// Characters a u-mode JS regex accepts escaped (outside a class / inside one).
const SYNTAX_CHARS = '^$\\.*+?()[]{}|/';
// The end of the input: no character follows (JS \s\S is every code unit).
const END_OF_INPUT = '(?![\\s\\S])';
const CLASS_ESCAPABLE = `${SYNTAX_CHARS}-`;

/**
 * The JS (u flag) source of the Python `re` pattern `py`. Only the constructs the spec
 * uses are translated; anything else throws, so a new construct is reviewed rather than
 * silently mistranslated (\s above all: JS \s is not Python's isspace).
 */
function translatePythonRegex(py) {
    let out = '';
    let inClass = false;
    for (let i = 0; i < py.length; i++) {
        const c = py[i];
        if (c === '\\') {
            const n = py[++i];
            if (n === 'd') out += DIGIT_CLASS_BODY; // a \p escape stands alone or in a class
            else if (n === 'w') out += inClass ? WORD_CLASS_BODY : `[${WORD_CLASS_BODY}]`;
            else if (n === 'r' || n === 'n') out += `\\${n}`;
            // Python's \Z is the end of the input (of the slice, with an endpos); JS $ without
            // the m flag is too, but Python's own $ is not (it also matches before a final \n),
            // so \Z gets a form no reader mistakes for either.
            else if (n === 'Z' && !inClass) out += END_OF_INPUT;
            else if (n !== undefined && (inClass ? CLASS_ESCAPABLE : SYNTAX_CHARS).includes(n)) out += `\\${n}`;
            else if (n === '-') out += '-';
            else throw new Error(`untranslated escape \\${n} in ${py}`);
        } else if (inClass) {
            if (c === '[') throw new Error(`nested [ in a class in ${py}`);
            if (c === ']') inClass = false;
            out += c;
        } else if (c === '[') {
            if (py[i + 1] === ']' || (py[i + 1] === '^' && py[i + 2] === ']')) throw new Error(`leading ] in a class in ${py}`);
            inClass = true;
            out += c;
        } else if (c === '(' && py[i + 1] === '?') {
            const group = ['(?:', '(?=', '(?!', '(?<=', '(?<!'].find((g) => py.startsWith(g, i));
            if (group === undefined) throw new Error(`untranslated group at ${i} in ${py}`);
            out += group;
            i += group.length - 1;
        } else if ('.^$'.includes(c)) {
            throw new Error(`untranslated ${c} in ${py}: its semantics differ between Python and JS`);
        } else {
            out += c;
        }
    }
    if (inClass) throw new Error(`unterminated class in ${py}`);
    new RegExp(out, 'u');
    return out;
}

/** `s` as a literal in a u-mode JS regex. */
function literal(s) {
    return [...s].map((c) => (SYNTAX_CHARS.includes(c) ? `\\${c}` : codePointEscape(c, false))).join('');
}

/** `c` as regex source: printable ASCII as is, anything else as a \u escape. */
function codePointEscape(c, inClass) {
    const cp = c.codePointAt(0);
    if (inClass && CLASS_ESCAPABLE.includes(c)) return `\\${c}`;
    if (cp > 0x20 && cp < 0x7f) return c;
    return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`;
}

/** The body of a character class holding exactly `chars` (no JS \s: see the header of the rule file). */
function classBody(chars) {
    return chars.map((c) => codePointEscape(c, true)).join('');
}

const byLengthDesc = (xs) => [...xs].sort((a, b) => [...b].length - [...a].length);
const combos = (heads, tails) => byLengthDesc(heads.flatMap((h) => tails.map((t) => h + t)));
const alt = (sources) => `(?:${sources.join('|')})`;

/**
 * A regex matching what the lexer matches when it tries the literal `entries` in order
 * and takes the first one that matches followed by `tail` (a lookahead source): entry k
 * is excluded where an earlier entry sharing its start also matches. Only an entry that
 * is a prefix of entry k or has entry k as a prefix can match where entry k does, and
 * an entry with an earlier prefix of itself is still reachable (the earlier one's tail
 * may fail), so both relations exclude. `keep` drops branches after the exclusions are
 * built from the full list.
 */
function firstOf(entries, tail = '', keep = () => true) {
    return alt(entries.flatMap((entry, k) => {
        if (!keep(entry)) return [];
        const earlier = entries.slice(0, k).filter((e) => e.startsWith(entry) || entry.startsWith(e));
        const exclude = earlier.length ? `(?!${alt(earlier.map(literal))}${tail})` : '';
        return [`${exclude}${literal(entry)}${tail}`];
    }));
}

// --- the spec ------------------------------------------------------------------------

function readSpec() {
    const spec = JSON.parse(fs.readFileSync(SPEC_PATH, 'utf8'));
    if (spec.version !== SPEC_VERSION) {
        throw new Error(`test/word-boundary.json is spec version ${spec.version}; this generator implements ` +
            `version ${SPEC_VERSION}. Review the spec steps against completionWordSpan and the wordPattern, then bump SPEC_VERSION.`);
    }
    if (spec.columns !== 'code points') throw new Error(`unexpected columns: ${spec.columns}`);
    return spec;
}

/** `chars` (one-character strings) as one string, each a single UTF-16 unit. */
function bmpChars(name, chars) {
    for (const c of chars) {
        if (c.length !== 1) throw new Error(`${name}: ${JSON.stringify(c)} is no single BMP character; the UTF-16 walks assume one unit`);
    }
    return chars.join('');
}

// The label of each token pattern, in the order the lexer tries them (_token_patterns).
const TOKEN_LABELS = [
    'opening', 'closing', 'string', 'dangling-quote', 'meta-indicator', 'bad-prefix', 'comment',
    'number', 'comma', 'symbol', 'new-line', 'spaces',
];

/**
 * The lexer's token regex in code (`inField` false), at a field's own level (`fieldLevel`)
 * or inside a field's brackets: each pattern a capture group, in TOKEN_LABELS order, as
 * lispython's _token_patterns assembles them from the pieces the spec publishes.
 *
 * Python's $ (no MULTILINE) also matches before a final \n, JS $ (no m flag) only at the
 * input's end; every lookahead taking $ here also takes \n (a stop, form-end and
 * number-end character, checked below), so both accept the same positions. Python's
 * possessive ++ and *+ are plain + and * here: each ends its pattern (nothing after it
 * could make the regex give characters back), so the match is the same; Python needs
 * them only against its backtracking memory.
 */
function tokenRegex(rule, inField, fieldLevel) {
    for (const [name, chars] of [['stopChars', rule.stopChars], ['formEndChars', rule.formEndChars], ['numberEndChars', rule.numberEndChars]]) {
        if (!chars.includes('\n')) throw new Error(`${name} lacks \\n: Python's $ and JS's $ would differ`);
    }
    const S = classBody(rule.stopChars);
    const F = classBody(rule.formEndChars);
    const N = classBody(rule.numberEndChars);
    const delimiter = translatePythonRegex(rule.fieldDelimiter);
    const continuation = translatePythonRegex(rule.fieldContinuation);
    const symbolBackslash = translatePythonRegex(rule.fieldSymbolBackslash);
    const literals = (entries) => alt(byLengthDesc(entries).map(literal));
    let end = fieldLevel ? `$|${delimiter}` : '$';
    if (inField) end = `${continuation}|${end}`;
    // Longest first, as the lexer tries them; a bad prefix stands before any of them, so
    // before the shortest (each longer one starts with it).
    const escapedOpenings = byLengthDesc(rule.escapedStringOpenings);
    const shortestEscaped = escapedOpenings.at(-1);
    for (const e of escapedOpenings) {
        if (!e.startsWith(shortestEscaped)) throw new Error(`escaped opening ${e} does not start with ${shortestEscaped}`);
    }
    const escaped = escapedOpenings.map(literal);
    const quote = inField ? `${escaped.join('|')}|` : '';
    const stopAhead = inField ? `(?=[${S}]|${literal(shortestEscaped)}|${end})` : `(?=[${S}]|${end})`;
    const fieldClose = rule.fieldBraces[1];
    const [char, commentChar] = fieldLevel
        ? [`(?!${delimiter})[^${classBody([...rule.stopChars, rule.backslash])}]`,
            `(?!${delimiter})[^${classBody([...rule.lineBreakChars, fieldClose])}]`]
        : [`[^${classBody([...rule.stopChars, rule.backslash])}]`, `[^${classBody(rule.lineBreakChars)}]`];
    const wrapper = literals(rule.wrappers);
    const opening = literals(rule.openings);
    const meta = literals(rule.metaChars);
    const patterns = {
        opening: `${wrapper}${opening}`,
        closing: literals(rule.closings),
        string: `${translatePythonRegex(rule.stringPrefix)}(?:${quote}${byLengthDesc(rule.stringOpenings).map(literal).join('|')})`,
        'dangling-quote': `${wrapper}${literals(rule.danglingQuotes)}(?=[${F}]|${end})`,
        'meta-indicator': `${wrapper}${meta}(?![${F}]|${end})`,
        'bad-prefix': `\\^\\*+(?:${opening}|${meta}|${stopAhead})`,
        comment: `;(?:${commentChar})*`,
        number: `(?:${translatePythonRegex(rule.numberToken)})(?=[${N}]|${end})`,
        comma: ',',
        symbol: inField ? `(?:${char}|${symbolBackslash})+${fieldLevel ? `|${delimiter}` : ''}` : `[^${S}]+`,
        'new-line': '\\n',
        spaces: inField ? `(?: |${continuation})+` : ' +',
    };
    const source = TOKEN_LABELS.map((label) => `(${patterns[label]})`).join('|');
    // The label is read off which group matched, so the pieces must hold no group of their own.
    const groups = new RegExp(`(?:${source})|`, 'u').exec('').length - 1;
    if (groups !== TOKEN_LABELS.length) throw new Error(`the token regex has ${groups} groups, not ${TOKEN_LABELS.length}`);
    return source;
}

/** The rule as JS-ready tables and regex sources: the body of wordBoundaryRule(). */
function jsRule(rule) {
    const stopChars = bmpChars('stopChars', rule.stopChars);
    const formEndChars = rule.formEndChars.join('');
    const numberEndChars = rule.numberEndChars.join('');
    if (rule.kindLetters.some(([letter]) => letter.length !== 1)) throw new Error('a kindLetters entry is no single letter');
    const nameRun = new RegExp(`^[${WORD_CLASS_BODY}]+$`, 'u');
    for (const name of rule.conversionNames) {
        if (!nameRun.test(name)) throw new Error(`conversion name ${JSON.stringify(name)} is no run of name characters`);
    }
    return {
        stopChars,
        formEndChars,
        numberEndChars,
        stopClass: classBody(rule.stopChars),
        formEndClass: classBody(rule.formEndChars),
        numberEndClass: classBody(rule.numberEndChars),
        alnum: `[${ALNUM_CLASS_BODY}]`,
        wrappers: byLengthDesc(rule.wrappers),
        openings: byLengthDesc(rule.openings),
        metaChars: byLengthDesc(rule.metaChars),
        danglingQuotes: byLengthDesc(rule.danglingQuotes),
        stringOpenings: byLengthDesc(rule.stringOpenings),
        // Spec order, not length order: the peel takes the FIRST entry the token starts with.
        tokenPrefixes: rule.tokenPrefixes,
        signs: rule.signs,
        signPeelFollowers: rule.signPeelFollowers,
        neverPeeled: rule.neverPeeled,
        stringPrefix: translatePythonRegex(rule.stringPrefix),
        numberToken: translatePythonRegex(rule.numberToken),
        signedComplex: translatePythonRegex(rule.signedComplex),
        // The scan (caretContext) and the run lex: the token regex of each context, and
        // the label of each of its groups.
        tokenLabels: TOKEN_LABELS,
        codeToken: tokenRegex(rule, false, false),
        fieldToken: tokenRegex(rule, true, true),
        bracketToken: tokenRegex(rule, true, false),
        closings: byLengthDesc(rule.closings),
        escapedStringOpenings: byLengthDesc(rule.escapedStringOpenings),
        rawLetter: rule.rawLetter,
        // The letters only: the first held makes the literal an f/t-string, and the lexer
        // reads both kinds alike (the kind's name only words lispython's messages).
        kindLetters: rule.kindLetters.map(([letter]) => letter),
        plainBodyStops: bmpChars('plainBodyStops', rule.plainBodyStops),
        interpolatedBodyStops: bmpChars('interpolatedBodyStops', rule.interpolatedBodyStops),
        fieldBraces: bmpChars('fieldBraces', rule.fieldBraces),
        backslash: rule.backslash,
        namedEscape: rule.namedEscape,
        quoteChars: bmpChars('quoteChars', rule.quoteChars),
        escapedQuote: rule.escapedQuote,
        bareQuote: rule.bareQuote,
        lineBreakChars: bmpChars('lineBreakChars', rule.lineBreakChars),
        whitespace: bmpChars('whitespace', rule.whitespace),
        fieldDelimiter: translatePythonRegex(rule.fieldDelimiter),
        // Compared whole against the name caretContext reads after a `!` (wordChar's run).
        conversionNames: rule.conversionNames,
        conversionEnds: bmpChars('conversionEnds', rule.conversionEnds),
        debugBlockers: bmpChars('debugBlockers', rule.debugBlockers),
        // A conversion's name character: Python's isalnum() or _ (\w over str).
        wordChar: `[${WORD_CLASS_BODY}]`,
    };
}

// --- the wordPattern -----------------------------------------------------------------

/**
 * The wordPattern: one match per dotted segment of the leaf, so VS Code's word at the
 * caret is the spec's [replaceStart, end]. A segment `[^STOP.]+` is matched only where
 * a lookbehind re-lexes its run from the run's start: run start, the run's leading
 * non-word tokens (each the lexer's choice at its position), the word token's start,
 * its peeled front (each peel the one the spec's peel loop takes), a "nothing more
 * peels" check at the leaf start, then the leaf's earlier segments. A symbol or number
 * token always runs to the run's end, so it is its run's last token and its leaf ends
 * there too. VS Code execs the regex from columns mid-line (getWordAtText's 15-column
 * windows), so a mid-segment start must fail, which this anchoring gives.
 *
 * Where the caret is inside the peeled front (`-|-x`) the spec's word starts at the
 * token, a caret-dependent span no regex can give; the word there is no match.
 *
 * ⚠️ The regex must never match the empty string: VS Code's
 * _findRegexMatchEnclosingPosition (wordHelper.ts) does not advance lastIndex past an
 * empty match and has no time-budget check in its inner loop, so it hangs the editor.
 */
function wordPattern(rule, js) {
    const S = js.stopClass;
    const F = js.formEndClass;
    const N = js.numberEndClass;
    const notStop = `[^${S}]`;
    const atRunEnd = `(?!${notStop})`; // next is a stop char or the line's end
    const atFormEnd = `(?![^${F}])`; // next is a formEndChars char or the line's end
    const atNumberEnd = `(?![^${N}])`; // next is a numberEndChars char or the line's end
    const beforeNonFormEnd = `(?=[^${F}])`; // next is a character, not a formEndChars one
    const hasStop = (s) => [...s].some((c) => rule.stopChars.includes(c));

    // Each lexer alternative, as tried at a token start; used whole in a lookahead it
    // answers "does this kind match here".
    const openings = combos(js.wrappers, js.openings);
    const dangling = combos(js.wrappers, js.danglingQuotes);
    const metas = combos(js.wrappers, js.metaChars);
    const badTails = byLengthDesc([...js.openings, ...js.metaChars]);
    const OPEN = alt(openings.map(literal));
    const STR = `${js.stringPrefix}${alt(js.stringOpenings.map(literal))}`;
    const DANG = `${alt(dangling.map(literal))}${atFormEnd}`;
    const META = `${alt(metas.map(literal))}${beforeNonFormEnd}`;
    const BAD = `\\^\\*+(?:${alt(badTails.map(literal))}|${atRunEnd})`;

    // The tokens that can precede the word token in its run: the lexer's choice at its
    // position, and stop-free, since a token holding a stop char reaches the run's end.
    // A dangling quote is followed by a formEndChars char, a stop char: never a lead.
    for (const c of rule.formEndChars) if (!rule.stopChars.includes(c)) throw new Error(`formEnd ${c} is not a stop char`);
    // A number token ends before a numberEndChars char, so it reaches its run's end only
    // while each of them is a stop char.
    for (const c of rule.numberEndChars) if (!rule.stopChars.includes(c)) throw new Error(`numberEnd ${c} is not a stop char`);
    const firstOfNoStop = (entries, tail) => firstOf(entries, tail, (e) => !hasStop(e));
    const leads = [
        firstOfNoStop(openings, ''),
        `(?!${OPEN})${js.stringPrefix}${firstOfNoStop(js.stringOpenings, '')}`,
        `(?!${alt([OPEN, STR, DANG])})${firstOfNoStop(metas, beforeNonFormEnd)}`,
        `(?!${alt([OPEN, STR, DANG, META])})\\^\\*+${firstOfNoStop(badTails, '')}`,
    ];
    const LEADS = `${alt(leads)}*`;
    const WORD_TOKEN_START = `(?!${alt([OPEN, STR, DANG, META, BAD])})`;

    // The peel loop. A peel step checks the rest (to the run's end) whole.
    const NEVER = `${alt(js.neverPeeled.map(literal))}${atRunEnd}`;
    const LONG = `(?=${notStop}{2})`; // at least 2 code points
    const PREFIX_STEP = `(?!${NEVER})${LONG}${firstOf(js.tokenPrefixes)}`;
    const SC_WHOLE = `(?:${js.signedComplex})${atRunEnd}`;
    const NUM_AT_WORD_START = `(?:${js.numberToken})${atNumberEnd}`; // the lexer's number test
    const NUM_WHOLE = `(?:${js.numberToken})${atRunEnd}`; // the type after a prefix peel
    const followers = alt([js.alnum, ...js.signPeelFollowers.map(literal)]);
    // A number whose signs are peeled starts with a sign, so only signedComplex blocks it.
    // `signs+` is maximal: a shorter run is followed by a sign, which is no follower.
    const signsStep = (isNumber) =>
        `(?!${NEVER})(?!(?=${isNumber})${SC_WHOLE})${LONG}${alt(js.signs.map(literal))}+(?=${followers})`;
    const noPeel = (isNumber) => `(?!${PREFIX_STEP})(?!${signsStep(isNumber)})`;
    // After a signs peel the rest starts with a follower, which starts no prefix or sign
    // (checked below), so nothing more peels; a prefix peel never leaves a number that
    // starts with a prefix, so prefix peels see a symbol.
    for (const s of [...js.tokenPrefixes, ...js.signs]) {
        if (new RegExp(`^${followers}`, 'u').test(s)) throw new Error(`${s} starts with a sign-peel follower`);
    }
    const FRONT = alt([
        noPeel(NUM_AT_WORD_START),
        signsStep(NUM_AT_WORD_START),
        `(?:${PREFIX_STEP})+${alt([noPeel(NUM_WHOLE), signsStep(NUM_WHOLE)])}`,
    ]);
    const EARLIER_SEGMENTS = `(?:[^${S}.]*\\.)*`;

    // A cheap first check, so the full lookbehind (which re-lexes back to the run's start)
    // runs at few columns: a segment starts after a run start, a lead token, a prefix
    // peel or a `.`, or right after a signs peel. A signs peel ends a maximal signs run
    // (it is followed by a follower, which is no sign) that starts at the word token, so
    // after a run start, a lead token or a prefix peel. ⚠️ Columns inside a signs run must
    // fail here, not in the full lookbehind: there each would re-lex the run, quadratic per
    // exec on a long `---…` line, enough to trip VS Code's time budget.
    const nonSignEnds = new Set();
    for (const e of [...openings, ...metas, ...badTails, ...js.stringOpenings, ...js.tokenPrefixes]) {
        nonSignEnds.add([...e].at(-1));
    }
    const signChars = new Set(js.signs.flatMap((s) => [...s]));
    for (const c of [...nonSignEnds, '.']) {
        if (signChars.has(c)) throw new Error(`${c} both ends a non-sign token and is a sign character`);
    }
    const ends = (chars) => classBody([...chars].filter((c) => !rule.stopChars.includes(c)));
    const SIGNS_RUN = `${alt(js.signs.map(literal))}+`;
    const guard = alt([
        `(?<=^|[${S}${ends([...nonSignEnds, '.'])}])`,
        `(?=${followers})(?<=(?:^|[${S}${ends(nonSignEnds)}])${SIGNS_RUN})`,
    ]);

    // A segment's first character is no `.` or stop char: checked first, so each column of
    // a `....` stretch after a lead or a peel fails before the full lookbehind.
    const pattern = `(?=[^${S}.])${guard}(?<=(?:^|[${S}])${LEADS}${WORD_TOKEN_START}${FRONT}${EARLIER_SEGMENTS})[^${S}.]+`;
    const re = new RegExp(pattern, 'gu');
    if (re.test('') || new RegExp(`^(?:${pattern})$`, 'u').test('')) throw new Error('the wordPattern matches the empty string');
    return pattern;
}

// --- the word separators -------------------------------------------------------------

// VS Code's classifier (wordCharacterClassifier.ts) makes space and tab whitespace
// whatever the setting lists, and a line never holds \n or \r: listing them adds nothing.
const CLASSIFIED_BY_VSCODE = [' ', '\t', '\n', '\r'];

/**
 * The [lispython] "editor.wordSeparators". Double-click (cursorWordOperations word()),
 * ctrl+left/right, ctrl+backspace/delete and Find's "match whole word" read this setting,
 * never the wordPattern, and it gives each character one class wherever it stands, so it
 * only approximates the spec: a separator is every character that always ends or starts
 * a token (stop chars, openings, meta chars, token prefixes), plus `.`, which splits the
 * leaf into its dotted segments (double-click selects the attribute, as in Python). The
 * signs are no separators, so `->f`, `as->` and `swap!` stay whole. What one class per
 * character cannot express: sign peeling, a meta char or prefix inside a symbol, a string
 * prefix's word, and the completion word across a dotted path. SEPARATOR_DIVERGENCES in
 * test/wordBoundary.test.js lists the spec cases of each.
 */
function wordSeparators(rule) {
    const chars = [
        ...rule.stopChars,
        ...rule.openings.flatMap((s) => [...s]),
        ...rule.metaChars.flatMap((s) => [...s]),
        ...rule.tokenPrefixes.flatMap((s) => [...s]),
        '.',
    ];
    const separators = [...new Set(chars)].filter((c) => !CLASSIFIED_BY_VSCODE.includes(c));
    for (const c of rule.signs.flatMap((s) => [...s])) {
        if (separators.includes(c)) throw new Error(`the sign character ${c} would be a word separator`);
    }
    for (const c of separators) if (c.length !== 1) throw new Error(`${c} is no single UTF-16 unit: VS Code classifies char codes`);
    return separators.join('');
}

/** `s` as an ASCII-only JSON string. */
function asciiJsonString(s) {
    return JSON.stringify(s).replace(/[^\x20-\x7e]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

/** package.json with `separators` as the [lispython] "editor.wordSeparators", the rest untouched. */
function packageSource(current, separators) {
    const scope = /"\[lispython\]"\s*:\s*/.exec(current);
    if (!scope) throw new Error('no "[lispython]" configurationDefaults in package.json');
    const objStart = scope.index + scope[0].length;
    const objEnd = jsonValueEnd(current, objStart);
    const obj = current.slice(objStart, objEnd);
    const value = asciiJsonString(separators);
    const key = /"editor\.wordSeparators"\s*:\s*/.exec(obj);
    let next;
    if (key) {
        const valueStart = key.index + key[0].length;
        next = obj.slice(0, valueStart) + value + obj.slice(jsonValueEnd(obj, valueStart));
    } else {
        const indent = /\n([ \t]*)"/.exec(obj)?.[1];
        if (indent === undefined) throw new Error('the "[lispython]" object has no property line to indent like');
        const body = obj.slice(0, obj.lastIndexOf('}')).trimEnd();
        next = `${body},\n${indent}"editor.wordSeparators": ${value}${obj.slice(body.length)}`;
    }
    const out = current.slice(0, objStart) + next + current.slice(objEnd);
    if (JSON.parse(out).contributes.configurationDefaults['[lispython]']['editor.wordSeparators'] !== separators) {
        throw new Error('the package.json edit missed contributes.configurationDefaults["[lispython]"]');
    }
    return out;
}

